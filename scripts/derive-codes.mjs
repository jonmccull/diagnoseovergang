// Amendment A.6 — derived entity cache.
// Collect every ICD-11 code referenced in content frontmatter (icd11[].code),
// union with the Chapter 06 grouping-level parent entities we always want warm,
// and write schema/derived-codes.json. Both the worker's scope allowlist and
// the nightly Cron pre-warm read this file, so the cached set scales with
// content and there is no manual sync point.
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { execSync } from "node:child_process";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const contentDir = join(root, "src", "content", "pd");

// Chapter 06 grouping/parent anchors to always keep warm (A.6 "plus the
// Chapter 06 grouping entities"), so a grouping stays cached even if an edit
// removes the last content reference to it. Every code here is verified to
// resolve in the pinned release; QE50.7 and the PD set stay via content refs.
const GROUPING_CODES = [
  "6A00", // Disorders of intellectual development
  "6A20", // Schizophrenia
  "6A40", // Catatonia
  "6A60", // Bipolar type I (mood anchor)
  "6B40", // Post traumatic stress disorder (stress anchor)
];

const codes = new Set(GROUPING_CODES);

for (const file of readdirSync(contentDir)) {
  if (!file.endsWith(".json")) continue;
  const entry = JSON.parse(readFileSync(join(contentDir, file), "utf8"));
  for (const ref of entry.icd11 ?? []) {
    if (ref?.code) codes.add(ref.code);
  }
}

const sorted = [...codes].sort();
const out = {
  // Generated by scripts/derive-codes.mjs — do not edit by hand.
  generatedFrom: "src/content/pd/*.json + GROUPING_CODES",
  codes: sorted,
};

writeFileSync(
  join(root, "schema", "derived-codes.json"),
  JSON.stringify(out, null, 2) + "\n"
);
console.log(`derive-codes: ${sorted.length} codes -> schema/derived-codes.json`);
console.log(sorted.join(" "));

// Content version for feedback anchoring (§9.2 contentVersion): the git commit
// at render time, so a re-anchoring job later knows which content a selection
// referenced. Falls back to "dev" outside a git checkout.
let contentVersion = "dev";
try {
  contentVersion = execSync("git rev-parse --short HEAD", {
    cwd: root,
    stdio: ["ignore", "pipe", "ignore"],
  })
    .toString()
    .trim();
} catch {
  // not a git checkout — keep "dev"
}
writeFileSync(
  join(root, "src", "content-version.ts"),
  `// Generated by scripts/derive-codes.mjs — do not edit.\n` +
    `export const CONTENT_VERSION = "${contentVersion}";\n`
);
console.log(`content-version: ${contentVersion} -> src/content-version.ts`);
